#!/usr/bin/env python3
"""Find frequent coauthors of the FAMLIES PIs/co-PIs and write coauthors.json.

A frequent coauthor has at least `min_papers` distinct publications (after
merging versions of the same paper) with a PI/co-PI since `since`, counted
from the PIs' OpenAlex records. Settings: "coauthors" in curation.json.
Run after fetch_openalex.py; then run fetch_coauthors.py and build_db.py.
"""
import collections
import json
import os
import re

import build_db as b

HERE = os.path.dirname(os.path.abspath(__file__))


def patterns(name):
    """Regexes for 'First ... Last' on ASCII-folded, lower-case names."""
    parts = [re.sub(r'[^a-z-]', '', x) for x in b.fold(name).split()]
    parts = [x for x in parts if x]
    first, last = parts[0], parts[-1]
    i = len(parts) - 1
    while i > 1 and parts[i - 1] in ('van', 'de', 'der', 'von', 'di', 'da', 'del', 'la', 'le'):
        i -= 1
    last = r'\s+'.join(parts[i:])
    return [rf'\b{first}\b.*\b{last}\b', rf'\b{last},\s*{first}\b']


def main():
    cur = json.load(open(os.path.join(HERE, 'curation.json')))
    cfg = cur['coauthors']
    people = b.load_people(coauthors=False)
    raw = b.from_openalex(people, cur) + b.from_flame() + b.from_bibfiles()
    kept = [r for r in raw if b.keep(r, people, cur)]
    groups = b.merge_groups(kept, cur.get('merge', []))

    pi_keys = {p['key'] for p in people if p['group'] == 'pi'}
    tracked = {i for p in people for i in p['openalex']}
    alias = cfg.get('aliases', {})
    count, names = collections.Counter(), {}
    for g in groups:
        if not {k for r in g for k in r['pis']} & pi_keys:
            continue
        if max(r['year'] or 0 for r in g) < cfg['since']:
            continue
        ids = set()
        for r in g:
            for name, aid in zip(r['authors'], r.get('author_ids', [])):
                if not aid or aid in tracked or b.pis_in([name], people):
                    continue
                aid = alias.get(aid, aid)
                ids.add(aid)
                names.setdefault(aid, name)
        count.update(ids)

    extra = collections.defaultdict(list)
    for a, main_id in alias.items():
        extra[main_id].append(a)
    out = []
    for aid, n in count.most_common():
        if n < cfg['min_papers'] or aid in cfg.get('exclude', []):
            continue
        name = cfg.get('names', {}).get(aid) or names[aid]
        out.append({
            'key': 'oa_' + aid.lower(),
            'name': name,
            'short': b.last_name(name),
            'group': 'coauthor',
            'role': 'Frequent coauthor',
            'institution': '',
            'orcid': '',
            'openalex': [aid] + extra.get(aid, []),
            'name_patterns': cfg.get('patterns', {}).get(aid) or patterns(name),
            'scholar': '',
            'papers_with_pis': n,
        })
    json.dump({'_comment': 'Generated by find_coauthors.py; edit curation.json instead.',
               'people': out}, open(os.path.join(HERE, 'coauthors.json'), 'w'),
              indent=2, ensure_ascii=False)
    print(f'{len(out)} frequent coauthors')
    for p in out:
        print(f'  {p["papers_with_pis"]:3d}  {p["name"]}')


if __name__ == '__main__':
    main()
